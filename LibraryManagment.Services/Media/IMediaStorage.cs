using LibraryManagement.Models.Options;
using Microsoft.Extensions.Hosting;
using Microsoft.Extensions.Options;

namespace LibraryManagement.Services.Media
{
    // Where uploaded files are kept. Chosen by "Storage:Provider" in appsettings.json.
    public interface IMediaStorage
    {
        // Saves the file and returns the public URL it is served from
        Task<string> SaveAsync(Stream content, string storedFileName, string contentType, CancellationToken cancellationToken = default);
        Task DeleteAsync(string storedFileName, CancellationToken cancellationToken = default);
    }

    // Files on the API server's disk, served by the API under Storage:Local:RequestPath (see UseMediaFiles)
    public class LocalMediaStorage : IMediaStorage
    {
        private readonly string _rootPath;
        private readonly string _requestPath;

        public LocalMediaStorage(IOptions<StorageOptions> options, IHostEnvironment environment)
        {
            _rootPath = ResolveRootPath(options.Value.Local, environment.ContentRootPath);
            _requestPath = "/" + options.Value.Local.RequestPath.Trim('/');
            Directory.CreateDirectory(_rootPath);
        }

        public static string ResolveRootPath(LocalStorageOptions options, string contentRootPath)
            => Path.GetFullPath(Path.Combine(contentRootPath, options.RootPath));

        public async Task<string> SaveAsync(Stream content, string storedFileName, string contentType, CancellationToken cancellationToken = default)
        {
            var path = FullPath(storedFileName);
            await using (var file = new FileStream(path, FileMode.CreateNew, FileAccess.Write, FileShare.None, 81920, useAsync: true))
            {
                await content.CopyToAsync(file, cancellationToken);
            }
            return $"{_requestPath}/{storedFileName}";
        }

        public Task DeleteAsync(string storedFileName, CancellationToken cancellationToken = default)
        {
            var path = FullPath(storedFileName);
            if (File.Exists(path))
            {
                File.Delete(path);
            }
            return Task.CompletedTask;
        }

        // Stored names are generated by the API, but never allow a path outside the uploads folder
        private string FullPath(string storedFileName)
        {
            var path = Path.GetFullPath(Path.Combine(_rootPath, Path.GetFileName(storedFileName)));
            if (!path.StartsWith(_rootPath, StringComparison.OrdinalIgnoreCase))
            {
                throw new InvalidOperationException("Invalid file name.");
            }
            return path;
        }
    }
}
